export function relativeDate(value, language, now = Date.now()) {
  if (!value) return '';
  const date = new Date(value),
    today = new Date(now);
  if (date.toDateString() === today.toDateString()) return messages[language].timeToday;
  today.setDate(today.getDate() - 1);
  if (date.toDateString() === today.toDateString()) return messages[language].timeYesterday;
  return new Intl.DateTimeFormat(language === 'de' ? 'de-DE' : 'en-GB', {
    day: 'numeric',
    month: 'short',
  }).format(date);
}
